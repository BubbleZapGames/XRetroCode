import * as path from 'path';
import * as vscode from 'vscode';
import { R65Symbol, R65SymbolIndex, R65SymbolKind } from './symbolIndex';
import { wordAt } from './typeResolver';
import { R65ReferenceFinder, RefHit, readText, symbolKey } from './references';
import { SourceText } from './sourceText';
import { asmFileHits, asmLabels, implementorsOf, inlineAsmHits } from './asmReferences';
import { IDENTIFIER_RE, RESERVED_WORDS } from './r65Keywords';

export const OUTSIDE_PROJECT = 'Outside this project';
export const GENERATED_FILE = 'Generated file (rebuilt from its source)';

/** Files that mark a project's root, nearest first. */
const PROJECT_MARKERS = ['r65.toml', 'GNUmakefile', 'makefile', 'Makefile'];

const TYPE_KINDS = new Set([
  R65SymbolKind.Struct, R65SymbolKind.Enum, R65SymbolKind.Union, R65SymbolKind.Trait, R65SymbolKind.TypeAlias,
]);

/** Package code fetched by `r65pkg`: the next fetch overwrites it, so it's never edited. */
export function isPackageFile(uri: vscode.Uri): boolean {
  return uri.fsPath.replace(/\\/g, '/').includes('/.r65/deps/');
}

function norm(p: string): string {
  const n = p.replace(/\\/g, '/').replace(/\/+$/, '');
  return process.platform === 'win32' ? n.toLowerCase() : n;
}

function isUnder(file: string, dir: string): boolean {
  return norm(file).startsWith(norm(dir) + '/');
}

/**
 * The folder holding `r65.toml` (else a makefile) nearest above `uri`, no
 * higher than its workspace folder. Undefined when there's none.
 */
export async function projectRoot(uri: vscode.Uri): Promise<string | undefined> {
  const folder = vscode.workspace.workspaceFolders
    ?.map(f => f.uri.fsPath)
    .find(f => isUnder(uri.fsPath, f));
  let dir = path.dirname(uri.fsPath);
  for (;;) {
    for (const name of PROJECT_MARKERS) {
      try {
        const bytes = await vscode.workspace.fs.readFile(vscode.Uri.file(path.join(dir, name)));
        if (bytes.length > 0) return dir;
      } catch {
        // Not here
      }
    }
    const parent = path.dirname(dir);
    if (parent === dir || (folder !== undefined && norm(dir) === norm(folder))) return undefined;
    dir = parent;
  }
}

/** A file a tool writes (`// GENERATED by make - DO NOT EDIT`): the next build would undo a rename in it. */
export function isGeneratedSource(text: string): boolean {
  const head = text.split('\n').slice(0, 5).join('\n');
  return /DO NOT EDIT|^\s*\/\/\s*(?:auto-?)?generated\b/im.test(head);
}

function fail(message: string): never {
  throw new Error(message);
}

/**
 * Rename Symbol (F2). Matches it can't pin down, and every hit in assembly,
 * become edits that need confirmation, which opens the Refactor Preview.
 */
export class R65RenameProvider implements vscode.RenameProvider {
  private finder: R65ReferenceFinder;

  constructor(private index: R65SymbolIndex) {
    this.finder = new R65ReferenceFinder(index);
  }

  prepareRename(document: vscode.TextDocument, position: vscode.Position): { range: vscode.Range; placeholder: string } {
    const w = wordAt(document, position.line, position.character) ?? fail('Place the cursor on a name to rename it.');
    const source = new SourceText(document.uri, document.getText());
    const offset = source.offsetAt(w.line, w.start);
    const range = new vscode.Range(w.line, w.start, w.line, w.end);
    if (source.masked[offset] !== w.word[0]) fail("Names in comments and strings can't be renamed.");

    const prev = source.masked[offset - 1] ?? '';
    if (prev === '$') {
      if (!this.macroVariable(source, offset)) fail(`'$${w.word}' isn't inside a macro_rules! definition.`);
      return { range, placeholder: w.word };
    }
    if (prev === "'") fail("Loop labels can't be renamed.");
    if (/[0-9]/.test(prev)) fail("Numbers can't be renamed.");
    if (RESERVED_WORDS.has(w.word)) fail(`'${w.word}' is a keyword, type or register, so it can't be renamed.`);

    const target = this.finder.target(document, position);
    if (!target) {
      fail(`Can't rename '${w.word}': its declaration isn't in an indexed .r65 file. Names a macro declares can't be renamed.`);
    }
    if (target.kind === 'symbols') this.renamable(target.symbols, w.word);
    return { range, placeholder: w.word };
  }

  async provideRenameEdits(
    document: vscode.TextDocument, position: vscode.Position, newName: string, token?: vscode.CancellationToken
  ): Promise<vscode.WorkspaceEdit | undefined> {
    if (!IDENTIFIER_RE.test(newName)) fail(`'${newName}' isn't a valid R65 identifier.`);
    if (RESERVED_WORDS.has(newName)) fail(`'${newName}' is a keyword, type or register, so it can't be a name.`);
    this.prepareRename(document, position);

    const w = wordAt(document, position.line, position.character)!;
    const source = new SourceText(document.uri, document.getText());
    const offset = source.offsetAt(w.line, w.start);
    if (newName === w.word) return new vscode.WorkspaceEdit();
    if (isGeneratedSource(source.text)) {
      fail(`${vscode.workspace.asRelativePath(document.uri)} is a generated file; the next build would undo a rename in it.`);
    }

    if (source.masked[offset - 1] === '$') {
      return this.renameMacroVariable(source, offset, w.word, newName);
    }

    const target = this.finder.target(document, position)!;
    if (target.kind === 'local') {
      const { binding } = target;
      const re = new RegExp(`(?<!(?:^|[^.])\\.|\\$)\\b${newName}\\b`, 'g');
      for (const m of source.masked.matchAll(re)) {
        const at = m.index!;
        if ((at >= binding.start && at < binding.end) || at === binding.decl) {
          if (/::\s*$/.test(source.masked.substring(Math.max(0, at - 40), at))) continue;
          if (source.fieldKeyOwner(at, newName.length)) continue;
          const line = source.positionAt(at).line + 1;
          fail(`'${newName}' is already used in the scope of '${w.word}' (line ${line}).`);
        }
      }
      return buildEdit(this.finder.localHits(target.source, binding), newName);
    }

    const all = this.family(this.renamable(target.symbols, w.word));
    for (const t of all) {
      if (isGeneratedSource(await readText(t.uri))) {
        fail(`'${w.word}' is declared in a generated file (${vscode.workspace.asRelativePath(t.uri)}); rename it where that file is generated from.`);
      }
    }
    if (all.some(t => TYPE_KINDS.has(t.kind)) && !/^[A-Z]/.test(newName)) {
      fail('A type name must start with an uppercase letter.');
    }

    const root = await projectRoot(document.uri);
    const inRoot = (uri: vscode.Uri) => root === undefined || isUnder(uri.fsPath, root);
    const own = all.filter(t => inRoot(t.uri));
    // Declared in this project: copies elsewhere (another game's vendored lib)
    // are theirs. Declared outside it (a shared folder): every user needs the edit.
    const scoped = own.length > 0;
    const targets = scoped ? own : all;
    const inScope = (uri: vscode.Uri) => !isPackageFile(uri) && (!scoped || inRoot(uri));

    this.checkConflicts(targets, newName, inScope);

    const r65Files = (await vscode.workspace.findFiles('**/*.r65')).filter(inScope);
    const hits = await this.finder.symbolHits(w.word, targets, r65Files, token);
    if (!hits) return undefined;
    await this.checkShadowing(hits, newName);

    const labels = asmLabels(targets, this.index);
    if (labels.length > 0) {
      for (const uri of r65Files) hits.push(...inlineAsmHits(await readText(uri), uri, labels));
      for (const uri of (await vscode.workspace.findFiles('**/*.{asm,s,inc}')).filter(inScope)) {
        if (token?.isCancellationRequested) return undefined;
        hits.push(...asmFileHits(await readText(uri), uri, labels));
      }
    }
    // A use in a generated file comes back with the old name on the next build
    for (const uri of r65Files) {
      if (!isGeneratedSource(await readText(uri))) continue;
      for (const h of hits) {
        if (h.uri.toString() === uri.toString()) {
          h.certainty = 'likely';
          h.reason = GENERATED_FILE;
        }
      }
    }
    if (!scoped) {
      for (const h of hits) {
        if (!inRoot(h.uri)) {
          h.certainty = 'likely';
          h.reason = OUTSIDE_PROJECT;
        }
      }
    }
    return buildEdit(hits, newName);
  }

  /** The targets rename can edit: not impl blocks, nor package code. */
  private renamable(symbols: R65Symbol[], word: string): R65Symbol[] {
    const named = symbols.filter(s => s.kind !== R65SymbolKind.Impl);
    if (named.length === 0) fail(`Can't rename '${word}': it has no declaration in an indexed .r65 file.`);
    const editable = named.filter(s => !isPackageFile(s.uri));
    if (editable.length === 0) fail(`'${word}' is declared in a package under .r65/deps/, which r65pkg overwrites.`);
    return editable;
  }

  /**
   * Everything that must keep the same name for the program to compile: a
   * trait's method or const, and that member in every `impl Trait for X`,
   * starting from either end.
   */
  private family(targets: R65Symbol[]): R65Symbol[] {
    const out = new Map<string, R65Symbol>();
    const add = (s: R65Symbol) => { if (!isPackageFile(s.uri)) out.set(symbolKey(s), s); };
    const traits = new Set(this.index.allSymbols().filter(s => s.kind === R65SymbolKind.Trait).map(s => s.name));
    const hasMember = (container: string, name: string) =>
      this.index.membersOfContainer(container).some(m => m.name === name);

    for (const t of targets) {
      add(t);
      if (!t.container || (t.kind !== R65SymbolKind.Function && t.kind !== R65SymbolKind.Constant)) continue;
      const owning = traits.has(t.container)
        ? [t.container]
        : [...this.index.traitsImplementedBy(t.container)].filter(tr => hasMember(tr, t.name));
      for (const trait of owning) {
        for (const container of [trait, ...implementorsOf(trait, this.index)]) {
          for (const m of this.index.membersOfContainer(container)) {
            if (m.name === t.name && m.kind === t.kind) add(m);
          }
        }
      }
    }
    return [...out.values()];
  }

  /** Fail when `newName` is already declared where the targets live. */
  private checkConflicts(targets: R65Symbol[], newName: string, inScope: (uri: vscode.Uri) => boolean): void {
    const where = (s: R65Symbol) => `${vscode.workspace.asRelativePath(s.uri)}:${s.selectionRange.start.line + 1}`;
    for (const t of targets) {
      if (t.container) {
        const clash = this.index.membersOfContainer(t.container).find(m => m.name === newName && inScope(m.uri));
        if (clash) fail(`'${t.container}' already has a member '${newName}' (${where(clash)}).`);
        continue;
      }
      const isMacro = t.kind === R65SymbolKind.Macro;
      const clash = this.index.lookup(newName).find(s =>
        !s.container && s.kind !== R65SymbolKind.Impl && inScope(s.uri) &&
        (s.kind === R65SymbolKind.Macro) === isMacro
      );
      if (clash) fail(`'${newName}' is already declared (${where(clash)}); R65 has one global namespace.`);
    }
  }

  /** Fail when a renamed use would be captured by a local already named `newName`. */
  private async checkShadowing(hits: RefHit[], newName: string): Promise<void> {
    const byFile = new Map<string, RefHit[]>();
    for (const h of hits) byFile.set(h.uri.toString(), [...(byFile.get(h.uri.toString()) ?? []), h]);
    for (const fileHits of byFile.values()) {
      const uri = fileHits[0].uri;
      const source = new SourceText(uri, await readText(uri));
      for (const h of fileHits) {
        const at = source.offsetAt(h.range.start.line, h.range.start.character);
        if (/(?:(?<!\.)\.|::)\s*$/.test(source.masked.substring(Math.max(0, at - 40), at))) continue;
        if (source.fieldKeyOwner(at, h.range.end.character - h.range.start.character)) continue;
        if (source.bindingAt(newName, at)) {
          fail(`A local '${newName}' would hide the renamed use at ${vscode.workspace.asRelativePath(uri)}:${h.range.start.line + 1}.`);
        }
      }
    }
  }

  /** The `macro_rules!` whose definition holds `offset`, as [start, end] offsets. */
  private macroVariable(source: SourceText, offset: number): [number, number] | undefined {
    let found: [number, number] | undefined;
    for (const m of source.masked.matchAll(/\bmacro_rules\s*!\s*[a-zA-Z_][a-zA-Z0-9_]*/g)) {
      if (m.index! > offset) break;
      const open = source.masked.indexOf('{', m.index! + m[0].length);
      if (open < 0) continue;
      const close = source.matchingBrace(open);
      if (offset <= close) found = [m.index!, close];
    }
    return found;
  }

  private renameMacroVariable(source: SourceText, offset: number, word: string, newName: string): vscode.WorkspaceEdit {
    const [from, to] = this.macroVariable(source, offset)!;
    const body = source.masked.substring(from, to + 1);
    if (new RegExp(`\\$${newName}\\b`).test(body)) fail(`This macro already has a '$${newName}'.`);
    const hits: RefHit[] = [];
    for (const m of body.matchAll(new RegExp(`\\$(${word})\\b`, 'g'))) {
      const at = from + m.index! + 1;
      hits.push({ uri: source.uri, range: source.range(at, word.length), kind: 'use', certainty: 'sure' });
    }
    return buildEdit(hits, newName);
  }
}

/** Sure hits as plain edits; the rest need confirmation, grouped by why. */
function buildEdit(hits: RefHit[], newName: string): vscode.WorkspaceEdit {
  const edit = new vscode.WorkspaceEdit();
  const seen = new Set<string>();
  for (const h of hits) {
    const key = `${h.uri.toString()}#${h.range.start.line}:${h.range.start.character}`;
    if (seen.has(key)) continue;
    seen.add(key);
    if (h.certainty === 'sure') {
      edit.replace(h.uri, h.range, newName);
    } else {
      edit.replace(h.uri, h.range, newName, { needsConfirmation: true, label: h.reason ?? 'Unconfirmed match' });
    }
  }
  return edit;
}
