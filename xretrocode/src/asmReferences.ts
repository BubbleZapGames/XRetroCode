import * as vscode from 'vscode';
import { R65Symbol, R65SymbolIndex, R65SymbolKind } from './symbolIndex';
import { RefHit } from './references';
import { maskCode } from './sourceText';

export const ASM_REFERENCE = 'Assembly reference';
export const INLINE_ASM = 'Inline asm!';

/** The file r65c writes starts with this banner; the build rewrites it, so it's never edited. */
const GENERATED_BANNER = 'Generated by R65 Compiler';

/**
 * A label the compiler emits for a symbol, as WLA-DX sees it: `before` + the
 * renamed `word`, then either the label's end or (`tail`) a `__member` suffix.
 */
export interface AsmLabel {
  before: string;
  word: string;
  tail: boolean;
}

const TYPE_KINDS = new Set([
  R65SymbolKind.Struct, R65SymbolKind.Enum, R65SymbolKind.Union, R65SymbolKind.Trait, R65SymbolKind.TypeAlias,
]);

/**
 * Labels the targets reach assembly under. Names go to WLA-DX verbatim, but a
 * method is `Type__method` and a variant constructor `Enum__Variant`
 * (R65 `hir/builder.py`, `hir/expression_builder.py`); a const is inlined and
 * a field, macro or local has no label at all.
 */
export function asmLabels(targets: R65Symbol[], index: R65SymbolIndex): AsmLabel[] {
  const labels = new Map<string, AsmLabel>();
  const add = (before: string, word: string, tail = false) => labels.set(`${before}|${word}|${tail}`, { before, word, tail });
  const traits = new Set(index.allSymbols().filter(s => s.kind === R65SymbolKind.Trait).map(s => s.name));

  for (const t of targets) {
    if (TYPE_KINDS.has(t.kind)) {
      add('', t.name, true);
    } else if (t.kind === R65SymbolKind.Function || t.kind === R65SymbolKind.Static) {
      if (!t.container) {
        add('', t.name);
      } else {
        add(`${t.container}__`, t.name);
        if (traits.has(t.container)) {
          for (const type of implementorsOf(t.container, index)) add(`${type}__`, t.name);
        }
      }
    } else if (t.kind === R65SymbolKind.EnumMember && t.container) {
      add(`${t.container}__`, t.name);
    }
  }
  return [...labels.values()];
}

/** Types with an `impl Trait for Type`. */
export function implementorsOf(trait: string, index: R65SymbolIndex): string[] {
  const types: string[] = [];
  for (const s of index.allSymbols()) {
    const m = s.kind === R65SymbolKind.Impl ? s.name.match(/^(\S+) for (\S+)$/) : null;
    if (m && m[1] === trait) types.push(m[2]);
  }
  return types;
}

function labelRegex(label: AsmLabel): RegExp {
  const end = label.tail ? '(?=__[A-Za-z0-9_])' : '(?![A-Za-z0-9_])';
  return new RegExp(`(?<![A-Za-z0-9_])${label.before}${label.word}${end}`, 'g');
}

/** Hits in `text` (already masked to what may hold labels), each on the renamed word only. */
function scan(masked: string[], uri: vscode.Uri, labels: AsmLabel[], reason: string): RefHit[] {
  const hits: RefHit[] = [];
  for (const label of labels) {
    const re = labelRegex(label);
    masked.forEach((line, i) => {
      for (const m of line.matchAll(re)) {
        const col = m.index! + label.before.length;
        hits.push({
          uri, range: new vscode.Range(i, col, i, col + label.word.length),
          kind: 'use', certainty: 'likely', reason,
        });
      }
    });
  }
  return hits;
}

export function isGeneratedAsm(text: string): boolean {
  return text.substring(0, 2000).includes(GENERATED_BANNER);
}

/** A WLA-DX source line with its `;` comment and string literals blanked. */
export function maskAsmLine(line: string): string {
  let out = '';
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (ch === ';') return out + ' '.repeat(line.length - i);
    if (ch === '"') {
      const close = line.indexOf('"', i + 1);
      const end = close < 0 ? line.length : close + 1;
      out += ' '.repeat(end - i);
      i = end - 1;
      continue;
    }
    out += ch;
  }
  return out;
}

/** References to `labels` in a hand-written assembly file. */
export function asmFileHits(text: string, uri: vscode.Uri, labels: AsmLabel[]): RefHit[] {
  if (labels.length === 0 || isGeneratedAsm(text)) return [];
  return scan(text.split('\n').map(maskAsmLine), uri, labels, ASM_REFERENCE);
}

/** References to `labels` inside the string arguments of an R65 file's `asm!(...)` statements. */
export function inlineAsmHits(text: string, uri: vscode.Uri, labels: AsmLabel[]): RefHit[] {
  if (labels.length === 0) return [];
  const lines = text.split('\n');
  const code = maskCode(lines, true);
  // Everything blank but the contents of strings inside `asm!( ... )`
  const strings = lines.map(l => ' '.repeat(l.length).split(''));
  let inAsm = false;
  let depth = 0;
  for (let i = 0; i < code.length; i++) {
    const line = code[i];
    for (let c = 0; c < line.length; c++) {
      if (!inAsm) {
        const m = line.substring(c).match(/^asm\s*!\s*\(/);
        if (m && !/[A-Za-z0-9_]/.test(line[c - 1] ?? '')) {
          inAsm = true;
          depth = 1;
          c += m[0].length - 1;
        }
        continue;
      }
      const ch = line[c];
      if (ch === '"') {
        const start = c;
        c++;
        while (c < line.length && line[c] !== '"') {
          if (line[c] === '\\') c++;
          c++;
        }
        for (let k = start + 1; k < Math.min(c, line.length); k++) strings[i][k] = lines[i][k];
        continue;
      }
      if (ch === '(') depth++;
      else if (ch === ')' && --depth === 0) inAsm = false;
    }
  }
  return scan(strings.map(s => s.join('')), uri, labels, INLINE_ASM);
}
